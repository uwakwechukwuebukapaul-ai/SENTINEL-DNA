"""
Sentinel DNA Investigation Result

Standard result contract returned by investigation execution.
"""

from __future__ import annotations

from datetime import datetime, timezone
from typing import Any


class InvestigationResult:
    """
    Immutable-style investigation execution result.

    Maintains findings generated by intelligence engines.
    """

    def __init__(
        self,
        case_id: str,
        status: str = "completed",
        findings: dict[str, Any] | None = None,
        iocs: list[Any] | None = None,
        entities: list[Any] | None = None,
        metadata: dict[str, Any] | None = None,
    ) -> None:

        self.case_id = case_id

        self.status = status

        self.findings = (
            dict(findings)
            if findings
            else {}
        )

        self.iocs = (
            iocs
            if iocs is not None
            else []
        )

        self.entities = (
            entities
            if entities is not None
            else []
        )

        self.metadata = (
            metadata
            if metadata is not None
            else {}
        )

        self.created_at = (
            datetime.now(
                timezone.utc
            ).isoformat()
        )


    def add_finding(
        self,
        name: str,
        value: Any,
    ) -> None:

        self.findings[name] = value


    def merge_findings(
        self,
        findings: dict[str, Any],
    ) -> None:

        if findings:
            self.findings.update(
                findings
            )


    def to_dict(
        self,
    ) -> dict[str, Any]:

        return {
            "case_id": self.case_id,
            "status": self.status,
            "findings": self.findings,
            "iocs": self.iocs,
            "entities": self.entities,
            "metadata": self.metadata,
            "created_at": self.created_at,
        }